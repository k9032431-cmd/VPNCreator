def plain(name: str) -> str:
    return EMOJI.get(name, ("", ""))[0]


def icon_id(name: str) -> str | None:
    return EMOJI.get(name, ("", ""))[1] or None


def e(name: str) -> str:
    """Эмодзи для текста сообщения (HTML parse mode)."""
    char, cid = EMOJI.get(name, ("", ""))
    if cid:
        return f'<tg-emoji emoji-id="{escape(cid)}">{char}</tg-emoji>'
    return char
